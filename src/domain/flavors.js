export function getFlavorById(id) {
  return FLAVORS.find(f => f.id === id) || FLAVORS[0];
}

export function getFlavorByIndex(idx) {
  const norm = ((idx % FLAVORS.length) + FLAVORS.length) % FLAVORS.length;
  return FLAVORS[norm];
}

